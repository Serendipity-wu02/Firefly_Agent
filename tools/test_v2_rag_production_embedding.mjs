test("9. Incremental Update: Force re-indexing only mutates updated content", async () => {
  const store = new InMemoryVectorStore();
  const provider = new DeterministicEmbeddingProvider({ dimension: 32 });
  const indexService = new VectorIndexService(store, provider);

  const chunk = { id: "c1", documentId: "d1", sourceUri: "s1", chunkIndex: 0, chunkType: "atomic_fact", text: "原始内容", tokenEstimate: 5, entityNames: [], keywords: [], canonicalPriority: 1, metadata: { perspective: "first_person", sourceFile: "s1", characters: [], verified: true } };
  await indexService.indexChunks([chunk]);

  const chunkUpdated = { ...chunk, text: "更新后内容" };
  await indexService.indexChunks([chunkUpdated], { forceReindex: true });

  const fetched = await store.get("c1");
  assert.equal(fetched.text, "更新后内容");
});

test("10. Deleted Source Cleanup: Purges records when sources are removed", async () => {
  const store = new InMemoryVectorStore();
  const provider = new DeterministicEmbeddingProvider({ dimension: 32 });
  const indexService = new VectorIndexService(store, provider);

  const c1 = { id: "c1", documentId: "d1", sourceUri: "valid.md", chunkIndex: 0, chunkType: "atomic_fact", text: "t1", tokenEstimate: 5, entityNames: [], keywords: [], canonicalPriority: 1, metadata: { perspective: "first_person", sourceFile: "valid.md", characters: [], verified: true } };
  const c2 = { id: "c2", documentId: "d2", sourceUri: "deleted.md", chunkIndex: 0, chunkType: "atomic_fact", text: "t2", tokenEstimate: 5, entityNames: [], keywords: [], canonicalPriority: 1, metadata: { perspective: "first_person", sourceFile: "deleted.md", characters: [], verified: true } };

  await indexService.indexChunks([c1, c2]);
  assert.equal(await store.count(), 2);

  const deleted = await indexService.syncWithManifest({}, [c1]);
  assert.equal(deleted, 1);
  assert.equal(await store.count(), 1);
  assert.equal(await store.get("c2"), null);
});

