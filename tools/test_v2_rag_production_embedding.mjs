test("15-18. Golden Query Benchmark: Recall@1, Recall@3, Recall@5 and MRR Calculation", async () => {
  const chunks = JSON.parse(fs.readFileSync(chunksPath, "utf-8"));
  const goldenQueries = JSON.parse(fs.readFileSync(goldenQueriesPath, "utf-8"));
  const hybrid = new HybridRetriever({ chunks });

  let r1Hits = 0;
  let r3Hits = 0;
  let r5Hits = 0;
  let reciprocalRankSum = 0;

  for (const gq of goldenQueries) {
    const res = await hybrid.retrieve({
      queryText: gq.query,
      entities: gq.expectedEntities,
      topK: 5,
    });

    let foundRank = -1;
    for (let i = 0; i < res.items.length; i++) {
      const itemText = res.items[i].chunk.text;
      const hasHit = gq.expectedKeywords.some((kw) => itemText.includes(kw));
      if (hasHit) {
        foundRank = i + 1;
        break;
      }
    }

    if (foundRank === 1) r1Hits++;
    if (foundRank >= 1 && foundRank <= 3) r3Hits++;
    if (foundRank >= 1 && foundRank <= 5) r5Hits++;
    if (foundRank > 0) {
      reciprocalRankSum += 1.0 / foundRank;
    }
  }

  const n = goldenQueries.length;
  const recall1 = r1Hits / n;
  const recall3 = r3Hits / n;
  const recall5 = r5Hits / n;
  const mrr = reciprocalRankSum / n;

  console.log(`\n[Golden Retrieval Benchmark Results]`);
  console.log(`Total Golden Queries: ${n}`);
  console.log(`Recall@1: ${(recall1 * 100).toFixed(1)}% (${r1Hits}/${n})`);
  console.log(`Recall@3: ${(recall3 * 100).toFixed(1)}% (${r3Hits}/${n})`);
  console.log(`Recall@5: ${(recall5 * 100).toFixed(1)}% (${r5Hits}/${n})`);
  console.log(`MRR: ${mrr.toFixed(4)}`);

  assert.ok(recall1 >= 0.70, `Recall@1 expected >= 70%, got ${recall1}`);
  assert.ok(recall5 >= 0.85, `Recall@5 expected >= 85%, got ${recall5}`);
  assert.ok(mrr >= 0.75, `MRR expected >= 0.75, got ${mrr}`);
});

test("19. Canonical Priority Gating: Rejects irrelevant sources even with 1.0 canonical priority", () => {
  const irrelevantP1Chunk = {
    id: "chunk_p1",
    documentId: "doc_p1",
    sourceUri: "firefly.yaml",
    chunkIndex: 0,
    chunkType: "structured_persona",
    text: "【流萤人设】说话轻柔温和...",
    tokenEstimate: 10,
    headingPath: ["流萤"],
    entityNames: ["流萤"],
    keywords: ["温和"],
    canonicalPriority: 1.0,
    metadata: { perspective: "first_person", sourceFile: "firefly.yaml", characters: ["流萤"], verified: true },
  };

  const relevantWikiChunk = {
    id: "chunk_wiki",
    documentId: "doc_wiki",
    sourceUri: "wiki/NPC/阿兰.txt",
    chunkIndex: 0,
    chunkType: "character_profile",
    text: "【阿兰 百科】空间站防卫科负责人...",
    tokenEstimate: 10,
    headingPath: ["阿兰"],
    entityNames: ["阿兰"],
    keywords: ["阿兰", "防卫科"],
    canonicalPriority: 0.5,
    metadata: { perspective: "third_person", sourceFile: "wiki/NPC/阿兰.txt", characters: ["阿兰"], verified: true },
  };

  const reranker = new KnowledgeReranker();
  const lex = [{ chunk: relevantWikiChunk, lexicalScore: 0.9 }];
  const results = reranker.rerank({ queryText: "空间站防卫科阿兰" }, lex, []);

  assert.ok(results.length > 0);
  assert.equal(results[0].chunk.id, "chunk_wiki");
  assert.ok(!results.some((r) => r.chunk.id === "chunk_p1"));
});

test("20. Deterministic Result Ordering: Permuted candidate order produces 100% identical rankings", () => {
  const reranker = new KnowledgeReranker();
  const c1 = { chunk: { id: "a", canonicalPriority: 0.9, text: "t1", documentId: "d", sourceUri: "s", chunkIndex: 0, chunkType: "atomic_fact", tokenEstimate: 5, entityNames: [], keywords: [], metadata: {} }, lexicalScore: 0.5 };
  const c2 = { chunk: { id: "b", canonicalPriority: 0.9, text: "t2", documentId: "d", sourceUri: "s", chunkIndex: 0, chunkType: "atomic_fact", tokenEstimate: 5, entityNames: [], keywords: [], metadata: {} }, lexicalScore: 0.5 };

  const res1 = reranker.rerank({ queryText: "测试" }, [c1, c2], []);
  const res2 = reranker.rerank({ queryText: "测试" }, [c2, c1], []);

  assert.deepEqual(res1.map((r) => r.chunk.id), res2.map((r) => r.chunk.id));
});
