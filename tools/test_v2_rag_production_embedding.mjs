test("12. Vector Retrieval: Queries top matching candidates", async () => {
  const store = new InMemoryVectorStore();
  const provider = new DeterministicEmbeddingProvider({ dimension: 64 });

  const chunkA = { id: "ca", documentId: "da", sourceUri: "sa", chunkIndex: 0, chunkType: "atomic_fact", text: "格拉默铁骑装甲萨姆", tokenEstimate: 10, entityNames: [], keywords: [], canonicalPriority: 1, metadata: { perspective: "first_person", sourceFile: "sa", characters: [], verified: true } };
  const chunkB = { id: "cb", documentId: "db", sourceUri: "sb", chunkIndex: 0, chunkType: "atomic_fact", text: "贝洛伯格冰雪世界", tokenEstimate: 10, entityNames: [], keywords: [], canonicalPriority: 1, metadata: { perspective: "first_person", sourceFile: "sb", characters: [], verified: true } };

  const embA = await provider.embedText(chunkA.text);
  const embB = await provider.embedText(chunkB.text);
  await store.upsert([
    { chunkId: "ca", documentId: "da", sourceUri: "sa", embedding: embA, text: chunkA.text, canonicalPriority: 1, modelInfo: provider.modelInfo, createdAt: 1, updatedAt: 1 },
    { chunkId: "cb", documentId: "db", sourceUri: "sb", embedding: embB, text: chunkB.text, canonicalPriority: 1, modelInfo: provider.modelInfo, createdAt: 1, updatedAt: 1 },
  ]);

  const qv = await provider.embedText("萨姆");
  const res = await store.query(qv, 1);
  assert.equal(res.length, 1);
  assert.equal(res[0].chunkId, "ca");
});

